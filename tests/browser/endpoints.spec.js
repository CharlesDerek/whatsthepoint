const {test,expect}=require('@playwright/test');
const {spawn}=require('node:child_process');
const {once}=require('node:events');
let server;
test.use({ignoreHTTPSErrors:true});
test.beforeAll(async({request})=>{
  server=spawn(process.execPath,['scripts/endpoint-browser-server.cjs'],{stdio:['ignore','pipe','inherit']});
  await expect.poll(async()=>{try{return (await request.get('https://127.0.0.1:18443/healthz',{ignoreHTTPSErrors:true})).status();}catch{return 0;}},{timeout:15000}).toBe(200);
});
test.afterAll(async()=>{if(server && server.exitCode===null){const stopped=once(server,'exit');server.kill('SIGTERM');await stopped;}});
test('TLS portal enrolls an endpoint, exports a credential, publishes and quarantines',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('https://127.0.0.1:18443/');
  await page.getByLabel('Username',{exact:true}).fill('admin');
  await page.getByLabel('Password',{exact:true}).fill('endpoint-ui-test-password');
  await page.getByRole('button',{name:'Sign in to your console'}).click();
  await page.getByRole('button',{name:'Endpoints',exact:true}).click();
  await page.getByRole('button',{name:'Enroll an endpoint'}).click();
  await page.getByLabel('Endpoint name').fill('Managed test laptop');
  await page.getByLabel('Management server IP:port').fill('192.0.2.10:18443');
  await page.getByLabel('Approved physical interfaces').fill('eth0');
  await page.getByLabel('Approved DNS server IPs').fill('192.0.2.53');
  await page.getByLabel('Approved TCP destinations').fill('192.0.2.20:443');
  await page.getByRole('button',{name:'Create enrollment file'}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download enrollment JSON'}).click();
  const file=await download;const chunks=[];for await(const chunk of await file.createReadStream())chunks.push(chunk);
  const config=JSON.parse(Buffer.concat(chunks).toString());
  expect(config.token).toMatch(/^[a-f0-9]{64}$/);expect(config.public_key).toMatch(/^[a-f0-9]{64}$/);
  expect(config.portal).toBe('https://127.0.0.1:18443');expect(config.interfaces).toEqual(['eth0']);
  const row=page.getByRole('row').filter({hasText:'Managed test laptop'});
  await expect(row).toContainText('Revision 1');await expect(row).toContainText('Not enrolled');
  await row.getByRole('button',{name:'Edit policy'}).click();
  await expect(page.getByLabel('Approved physical interfaces')).toHaveAttribute('readonly','');
  await page.getByLabel('Approved TCP destinations').fill('192.0.2.30:443');
  await page.getByRole('button',{name:'Publish policy'}).click();await expect(row).toContainText('Revision 2');
  await row.getByRole('button',{name:'Quarantine',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();await expect(row).toContainText('Revision 3');
  await row.getByRole('button',{name:'Restore',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();await expect(row).toContainText('Revision 4');
  await page.screenshot({path:'artifacts/endpoints-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/endpoints-mobile.png',fullPage:true});expect(errors).toEqual([]);
});
