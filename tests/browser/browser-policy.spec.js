const {test,expect}=require('@playwright/test');
test('portal enrollment, group assignment, category rules and page diagnostics',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('Username',{exact:true}).fill('admin');
  await page.getByLabel('Password',{exact:true}).fill('browser-test-password');
  await page.getByRole('button',{name:'Sign in to your console'}).click();
  await page.getByRole('button',{name:'Browser protection',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Protection follows the desktop profile.'})).toBeVisible();
  await page.getByRole('button',{name:'Enroll a profile'}).click();
  await page.getByLabel('Profile name',{exact:true}).fill('Portal test profile');
  await page.getByLabel('Policy group',{exact:true}).fill('Students');
  await page.getByRole('button',{name:'Create profile token'}).click();
  await expect(page.getByLabel('New profile token')).toHaveValue(/^[a-f0-9]{64}$/);
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.getByRole('button',{name:'Add browser rule'}).click();
  await page.getByRole('combobox',{name:'Scope',exact:true}).selectOption('group');
  await page.getByLabel('Group name or profile ID').fill('Students');
  await page.getByRole('combobox',{name:'Match',exact:true}).selectOption('category');
  await page.getByLabel('Pattern',{exact:true}).fill('gambling');
  await page.getByRole('button',{name:'Save browser rule'}).click();
  await expect(page.getByRole('cell',{name:'group Students'})).toBeVisible();
  await page.getByRole('button',{name:'Test a page'}).click();
  await page.getByLabel('URL',{exact:true}).fill('https://example.org/');
  await page.getByLabel('Sample page text').fill('Online casino. Bet now.');
  await page.getByRole('button',{name:'Evaluate page'}).click();
  await expect(page.locator('#browser-preview-result')).toContainText('"action": "block"');
  await expect(page.locator('#browser-preview-result')).toContainText('gambling');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.screenshot({path:'artifacts/browser-policy-desktop.png',fullPage:true});
  const row=page.getByRole('row').filter({hasText:'Portal test profile'});
  await row.getByRole('button',{name:'Edit',exact:true}).click();
  await page.getByLabel('Policy group',{exact:true}).fill('Staff');
  await page.getByRole('button',{name:'Save profile'}).click();
  await expect(row).toContainText('Staff');
  await row.getByRole('button',{name:'New token'}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(page.getByLabel('New profile token')).toHaveValue(/^[a-f0-9]{64}$/);
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/browser-policy-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
